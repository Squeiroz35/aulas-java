package metodos;

public class calculametodos {
	public int somar(int a, int b) {
		return a+b;
		
	}
	public int somar2(int a, int b,int c) {
		return a + b + c;
		
}
	public int subtrair(int a, int b) {
		return a - b;
		}
	public int subtrair2(int a, int b,int c) {
		return a - b - c;
}
	public int multi(int a, int b) {
		return a * b;
}
	public int multi2(int a, int b,int c) {
		return a * b * c;	
}
	public int divisao(int a, int b) {
		return a / b;
}
	public int divisao2(int a, int b,int c) {
		return a / b / c;
	}
}